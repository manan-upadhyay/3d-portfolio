// Regenerates src/constants/commitHistory.js from THIS repo's real git log so the
// Making-Of commit graph can never silently drift from the source (persona audit
// 2026-07-05, item 6 — the skeptic dev checks this against the public repo).
//
// Runs as `prebuild`, before every `npm run build`. It is deliberately
// NON-FATAL: on a shallow clone (CI / Vercel default fetch-depth 1) or when git
// is unavailable, it keeps the committed snapshot and exits 0 — the build never
// breaks, and the file the developer committed from a full local clone stays the
// source of truth. `WINDOW_START` is an editorial choice (the start of the dense
// build burst); every count around it is regenerated and therefore always true.
import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const WINDOW_START = '2026-06-20'; // start of the dense build burst (framing only)
const OUT = fileURLToPath(new URL('../src/constants/commitHistory.js', import.meta.url));

const keep = (why) => {
  console.warn(`[commit-history] ${why} — keeping the committed snapshot.`);
  process.exit(0);
};

let raw;
try {
  raw = execSync('git log --all --pretty=%ad --date=format:%Y-%m-%d', { encoding: 'utf8' });
} catch {
  keep('git log failed');
}

const dates = raw.split('\n').map((s) => s.trim()).filter(Boolean);
// A shallow clone returns only the tip commit(s); refuse to overwrite real
// history with a stub. Five is a safe floor below any genuine build.
if (dates.length < 5) keep('shallow or empty history');

const counts = {};
for (const d of dates) counts[d] = (counts[d] || 0) + 1;
const ascending = Object.keys(counts).sort();
const first = ascending[0];
const last = ascending[ascending.length - 1];
// Newest → oldest in the file (matches the graph's "land on the latest day").
const days = Object.fromEntries(ascending.slice().reverse().map((d) => [d, counts[d]]));

const header = `// AUTO-GENERATED by scripts/gen-commit-history.mjs (runs as \`prebuild\`).
// Do NOT edit by hand — regenerate with \`npm run build\` (or \`node
// scripts/gen-commit-history.mjs\`). Every figure is straight from this repo's
// \`git log --all\` so the Making-Of graph can never drift false. \`windowStart\`
// frames the graph to the dense build burst; the earlier days stay recorded for
// truth but sit outside the "how this site was built" window.
`;
const body = `export const commitHistory = ${JSON.stringify({ total: dates.length, first, last, windowStart: WINDOW_START, days }, null, 2)};\n`;

writeFileSync(OUT, `${header}${body}`);
console.log(`[commit-history] wrote ${dates.length} commits · ${first} → ${last}.`);
